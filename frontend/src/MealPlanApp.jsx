// ---------- Shopping Tab ----------
function ShoppingTab({ settings, persist, anchor, today, cookWeekdays }) {
  // Food from a cook day is eaten starting the NEXT day, through and including the next cook day.
  const cookDate = nearestCookDate(cookWeekdays, today);
  const nextCookDate = nearestCookDate(cookWeekdays, addDays(cookDate, 1));
  const windowLen = diffDays(cookDate, nextCookDate);
  const windowDates = Array.from({ length: windowLen }, (_, i) => addDays(cookDate, i + 1));

  const lunchCount = {};
  const dinnerCount = {};
  const breakfastCount = {};
  windowDates.forEach((d) => {
    const m = mealsForDate(d, anchor, cookWeekdays);
    lunchCount[m.lunch] = (lunchCount[m.lunch] || 0) + 1;
    dinnerCount[m.dinner] = (dinnerCount[m.dinner] || 0) + 1;
    breakfastCount[m.breakfast] = (breakfastCount[m.breakfast] || 0) + 1;
  });

  const entries = [
    ...Object.entries(lunchCount).map(([id, portions]) => ({ id, portions })),
    ...Object.entries(dinnerCount).map(([id, portions]) => ({ id, portions })),
    ...Object.entries(breakfastCount).map(([id, portions]) => ({ id, portions })),
  ];
  const ingredients = aggregate(entries);
  const grouped = groupByCategory(ingredients);

  const cookItems = [];
  Object.entries(lunchCount).forEach(([id, count]) => {
    const k = LUNCH_IDS.indexOf(id) + 1;
    cookItems.push({ text: `${RECIPES[id].name} + ${RECIPES[DINNER_IDS[k - 1]].name}`, tag: count > 1 ? `x${count}` : 'x1' });
  });

  const shoppingDate = settings.shoppingTiming === 'before' ? addDays(cookDate, -1) : cookDate;

  return (
    <div>
      <section style={cardStyle}>
        <label style={labelStyle}>Готовок в неделю</label>
        <div style={{ display: 'flex', gap: 8, marginBottom: 10 }}>
          {[1, 2].map((n) => (
            <button
              key={n}
              onClick={() => persist({ ...settings, cookCount: n })}
              style={{
                flex: 1,
                padding: '8px 0',
                borderRadius: 10,
                border: settings.cookCount === n ? `1px solid ${COLORS.primary}` : `1px solid ${COLORS.line}`,
                background: settings.cookCount === n ? COLORS.primary : COLORS.panel,
                color: settings.cookCount === n ? '#fff' : COLORS.ink,
                fontWeight: 600,
                cursor: 'pointer',
              }}
            >
              {n} раз{n === 1 ? '' : 'а'}
            </button>
          ))}
        </div>

        <label style={labelStyle}>День готовки{settings.cookCount === 2 ? ' №1' : ''}</label>
        <select
          value={settings.cookWeekday1}
          onChange={(e) => persist({ ...settings, cookWeekday1: Number(e.target.value) })}
          style={inputStyle}
        >
          {WEEKDAY_FULL.map((name, i) => (
            <option key={i} value={i + 1}>{name}</option>
          ))}
        </select>

        {settings.cookCount === 2 && (
          <>
            <label style={{ ...labelStyle, marginTop: 10 }}>День готовки №2</label>
            <select
              value={settings.cookWeekday2}
              onChange={(e) => persist({ ...settings, cookWeekday2: Number(e.target.value) })}
              style={inputStyle}
            >
              {WEEKDAY_FULL.map((name, i) => (
                <option key={i} value={i + 1}>{name}</option>
              ))}
            </select>
          </>
        )}

        <label style={{ ...labelStyle, marginTop: 10 }}>Закупка</label>
        <div style={{ display: 'flex', gap: 8 }}>
          {[
            { id: 'same', label: 'В день готовки' },
            { id: 'before', label: 'За день до' },
          ].map((opt) => (
            <button
              key={opt.id}
              onClick={() => persist({ ...settings, shoppingTiming: opt.id })}
              style={{
                flex: 1,
                padding: '8px 4px',
                borderRadius: 10,
                border: settings.shoppingTiming === opt.id ? `1px solid ${COLORS.primary}` : `1px solid ${COLORS.line}`,
                background: settings.shoppingTiming === opt.id ? COLORS.primary : COLORS.panel,
                color: settings.shoppingTiming === opt.id ? '#fff' : COLORS.ink,
                fontWeight: 600,
                fontSize: 12,
                cursor: 'pointer',
              }}
            >
              {opt.label}
            </button>
          ))}
        </div>
      </section>

      <section style={{ ...cardStyle, marginTop: 14, borderLeft: `4px solid ${COLORS.accent}` }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'baseline' }}>
          <span style={{ fontFamily: 'ui-serif, Georgia, serif', fontWeight: 700, fontSize: 16 }}>Ближайшая закупка</span>
          <span style={{ fontSize: 12, color: COLORS.inkSoft }}>{fmtDate(shoppingDate)}</span>
        </div>
        <p style={{ fontSize: 12, color: COLORS.inkSoft, margin: '4px 0 0' }}>
          Готовка — {WEEKDAY_NAMES[isoWeekday(cookDate) - 1]} {fmtDate(cookDate)}. Едим с {WEEKDAY_NAMES[isoWeekday(windowDates[0]) - 1]} {fmtDate(windowDates[0])} по {WEEKDAY_NAMES[isoWeekday(nextCookDate) - 1]} {fmtDate(nextCookDate)} включительно ({windowLen} {windowLen === 1 ? 'день' : 'дня/дней'}).
        </p>

        <h3 style={{ fontSize: 13, color: COLORS.flame, margin: '12px 0 6px' }}>
          <ChefHat size={14} style={{ verticalAlign: '-2px', marginRight: 4 }} />
          Что готовить
        </h3>
        <ul style={{ margin: 0, paddingLeft: 18, fontSize: 13 }}>
          {cookItems.map((it, i) => (
            <li key={i} style={{ marginBottom: 2 }}>
              {it.text} <span style={{ color: COLORS.inkSoft }}>— {it.tag}</span>
            </li>
          ))}
        </ul>

        <h3 style={{ fontSize: 13, color: COLORS.flame, margin: '14px 0 6px' }}>
          <ShoppingCart size={14} style={{ verticalAlign: '-2px', marginRight: 4 }} />
          Что купить
        </h3>
        {grouped.map(({ cat, items }) => (
          <div key={cat} style={{ marginBottom: 8 }}>
            <div style={{ fontSize: 12, fontWeight: 700, color: COLORS.primarySoft, marginBottom: 2 }}>{cat}</div>
            <ul style={{ margin: 0, paddingLeft: 18, fontSize: 13 }}>
              {items.map((it) => (
                <li key={it.name}>
                  {it.name} — {fmtQty(it.qty)} {it.unit}
                </li>
              ))}
            </ul>
          </div>
        ))}
        <p style={{ fontSize: 11, color: COLORS.inkSoft, marginTop: 6, marginBottom: 0 }}>
          <Snowflake size={11} style={{ verticalAlign: '-1px' }} /> Если блюдо нужно &gt;1 раза за период — сразу разложите по порциям (часть в холодильник, часть в морозилку).
        </p>
      </section>
    </div>
  );
}

