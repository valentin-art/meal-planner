const LUNCH_IDS = ['l1', 'l2', 'l3', 'l4', 'l5'];
const DINNER_IDS = ['d1', 'd2', 'd3', 'd4', 'd5'];
const CAT_ORDER = ['Белок', 'Крупы', 'Овощи', 'Яйца и молочное', 'Прочее'];

function aggregate(entries) {
  const map = {};
  entries.forEach(({ id, portions }) => {
    RECIPES[id].ingredients.forEach((ing) => {
      const key = ing.name + '|' + ing.unit + '|' + ing.cat;
      map[key] = (map[key] || 0) + ing.qty * portions;
    });
  });
  return Object.entries(map)
    .map(([key, qty]) => {
      const [name, unit, cat] = key.split('|');
      return { name, unit, cat, qty: Math.round(qty * 10) / 10 };
    })
    .sort((a, b) => a.name.localeCompare(b.name, 'ru'));
}

function groupByCategory(list) {
  const groups = {};
  list.forEach((item) => {
    if (!groups[item.cat]) groups[item.cat] = [];
    groups[item.cat].push(item);
  });
  return CAT_ORDER.filter((c) => groups[c]).map((c) => ({ cat: c, items: groups[c] }));
}

function fmtQty(qty) {
  return Number.isInteger(qty) ? qty : qty.toFixed(2).replace(/\.?0+$/, '');
}

// ---------- Date helpers ----------
function startOfDay(d) {
  const x = new Date(d);
  x.setHours(0, 0, 0, 0);
  return x;
}
function diffDays(a, b) {
  return Math.round((startOfDay(b) - startOfDay(a)) / 86400000);
}
function addDays(d, n) {
  const x = new Date(d);
  x.setDate(x.getDate() + n);
  return x;
}
function isoWeekday(d) {
  const wd = d.getDay(); // Sun=0..Sat=6
  return wd === 0 ? 7 : wd;
}
function toISO(d) {
  const x = startOfDay(d);
  const y = x.getFullYear();
  const m = String(x.getMonth() + 1).padStart(2, '0');
  const day = String(x.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}
function fmtDate(d) {
  return d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
}
function dishIndexForDate(date, anchor) {
  const diff = diffDays(anchor, date);
  return (((diff % 5) + 5) % 5) + 1; // 1..5 — the underlying 5-day rotation, used to pick WHICH dishes land in a batch
}
function breakfastForDate(date, anchor) {
  const diff = diffDays(anchor, date);
  return (((diff % 2) + 2) % 2) === 0 ? 'b1' : 'b2';
}
const FISH_LUNCH_IDS = { l3: true, l5: true };
const FISH_DINNER_IDS = { d2: true, d3: true };
function fishPriority(k) {
  let p = 0;
  if (FISH_LUNCH_IDS[LUNCH_IDS[k - 1]]) p += 1;
  if (FISH_DINNER_IDS[DINNER_IDS[k - 1]]) p += 1;
  return p; // 0, 1, or 2 — higher means eat it sooner in the batch
}
function previousCookDate(cookWeekdays, from) {
  for (let i = 1; i <= 7; i++) {
    const d = addDays(from, -i);
    if (cookWeekdays.includes(isoWeekday(d))) return d;
  }
  return addDays(from, -7);
}
// Which dishes land in a batch is still driven by the plain 5-day rotation (dishIndexForDate),
// so the total ingredient list for any given batch never changes. What changes is the ORDER
// those dishes are eaten in within the batch: fish-containing dishes are always moved to the
// front (freshest days), meat-only dishes pushed to the back (they hold up longer in the fridge).
function mealsForDate(date, anchor, cookWeekdays) {
  const windowEnd = nearestCookDate(cookWeekdays, date);
  const windowStart = addDays(previousCookDate(cookWeekdays, windowEnd), 1);
  const winLen = diffDays(windowStart, windowEnd) + 1;
  const naturalKs = [];
  for (let i = 0; i < winLen; i++) naturalKs.push(dishIndexForDate(addDays(windowStart, i), anchor));
  const order = naturalKs.map((_, i) => i).sort((a, b) => fishPriority(naturalKs[b]) - fishPriority(naturalKs[a]) || a - b);
  const sortedKs = order.map((i) => naturalKs[i]);
  const pos = diffDays(windowStart, date);
  const k = sortedKs[Math.max(0, Math.min(pos, sortedKs.length - 1))];
  return { k, lunch: LUNCH_IDS[k - 1], dinner: DINNER_IDS[k - 1], breakfast: breakfastForDate(date, anchor) };
}
function dayTotals(meals) {
  const parts = [RECIPES[meals.breakfast], RECIPES[meals.lunch], RECIPES[meals.dinner]];
  return {
    kcal: parts.reduce((s, r) => s + r.kcal, 0),
    protein: parts.reduce((s, r) => s + r.protein, 0),
  };
}
function nextDateForWeekday(weekday, from) {
  for (let i = 0; i < 7; i++) {
    const d = addDays(from, i);
    if (isoWeekday(d) === weekday) return d;
  }
  return from;
}
function nearestCookDate(cookWeekdays, from) {
  let best = null;
  cookWeekdays.forEach((wd) => {
    const d = nextDateForWeekday(wd, from);
    if (!best || d < best) best = d;
  });
  return best;
}

